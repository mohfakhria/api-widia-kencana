CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS assets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    token UUID NOT NULL DEFAULT gen_random_uuid(),

    bucket TEXT NOT NULL,
    scope TEXT NOT NULL DEFAULT 'assets',
    object_name TEXT NOT NULL,

    original_filename TEXT NOT NULL,
    stored_filename TEXT NOT NULL,
    mime_type TEXT NOT NULL DEFAULT 'application/octet-stream',
    extension TEXT NOT NULL DEFAULT '',

    size BIGINT NOT NULL DEFAULT 0,
    etag TEXT NOT NULL DEFAULT '',
    checksum_sha256 TEXT,

    status TEXT NOT NULL DEFAULT 'pending',
    upload_method TEXT NOT NULL DEFAULT 'presigned_put',

    multipart_upload_id TEXT,
    multipart_part_size BIGINT,
    multipart_total_parts INTEGER,

    is_private BOOLEAN NOT NULL DEFAULT TRUE,

    uploaded_by BIGINT
        REFERENCES users (id)
        ON DELETE SET NULL,

    presigned_expires_at TIMESTAMPTZ,
    uploaded_at TIMESTAMPTZ,
    failed_at TIMESTAMPTZ,
    deleted_at TIMESTAMPTZ,

    failure_code TEXT,
    failure_message TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT assets_bucket_not_empty_chk
        CHECK (BTRIM(bucket) <> ''),

    CONSTRAINT assets_scope_not_empty_chk
        CHECK (BTRIM(scope) <> ''),

    CONSTRAINT assets_object_name_not_empty_chk
        CHECK (BTRIM(object_name) <> ''),

    CONSTRAINT assets_original_filename_not_empty_chk
        CHECK (BTRIM(original_filename) <> ''),

    CONSTRAINT assets_stored_filename_not_empty_chk
        CHECK (BTRIM(stored_filename) <> ''),

    CONSTRAINT assets_size_non_negative_chk
        CHECK (size >= 0),

    CONSTRAINT assets_multipart_part_size_chk
        CHECK (
            multipart_part_size IS NULL
            OR multipart_part_size > 0
        ),

    CONSTRAINT assets_multipart_total_parts_chk
        CHECK (
            multipart_total_parts IS NULL
            OR multipart_total_parts > 0
        ),

    CONSTRAINT assets_status_chk
        CHECK (
            status IN (
                'pending',
                'uploading',
                'uploaded',
                'failed',
                'deleted'
            )
        ),

    CONSTRAINT assets_upload_method_chk
        CHECK (
            upload_method IN (
                'direct',
                'presigned_put',
                'presigned_post',
                'multipart'
            )
        ),

    CONSTRAINT assets_multipart_fields_chk
        CHECK (
            upload_method = 'multipart'
            OR (
                multipart_upload_id IS NULL
                AND multipart_part_size IS NULL
                AND multipart_total_parts IS NULL
            )
        ),

    CONSTRAINT assets_uploaded_state_chk
        CHECK (
            status <> 'uploaded'
            OR uploaded_at IS NOT NULL
        ),

    CONSTRAINT assets_failed_state_chk
        CHECK (
            status <> 'failed'
            OR failed_at IS NOT NULL
        ),

    CONSTRAINT assets_deleted_state_chk
        CHECK (
            status <> 'deleted'
            OR deleted_at IS NOT NULL
        )
);

CREATE UNIQUE INDEX IF NOT EXISTS assets_bucket_object_name_uq_idx
    ON assets (bucket, object_name)
    WHERE deleted_at IS NULL;

CREATE UNIQUE INDEX IF NOT EXISTS assets_token_uq_idx
    ON assets (token);

CREATE INDEX IF NOT EXISTS assets_uploaded_by_idx
    ON assets (uploaded_by)
    WHERE deleted_at IS NULL;

CREATE INDEX IF NOT EXISTS assets_created_at_idx
    ON assets (created_at DESC);

CREATE INDEX IF NOT EXISTS assets_status_idx
    ON assets (status);

CREATE INDEX IF NOT EXISTS assets_scope_idx
    ON assets (scope);

CREATE INDEX IF NOT EXISTS assets_mime_type_idx
    ON assets (mime_type);

CREATE INDEX IF NOT EXISTS assets_extension_idx
    ON assets (extension);

CREATE INDEX IF NOT EXISTS assets_uploaded_by_created_at_idx
    ON assets (uploaded_by, created_at DESC)
    WHERE deleted_at IS NULL;

CREATE INDEX IF NOT EXISTS assets_uploaded_by_scope_created_at_idx
    ON assets (uploaded_by, scope, created_at DESC)
    WHERE deleted_at IS NULL;

CREATE INDEX IF NOT EXISTS assets_pending_expiry_idx
    ON assets (presigned_expires_at)
    WHERE status IN ('pending', 'uploading')
      AND deleted_at IS NULL;

CREATE INDEX IF NOT EXISTS assets_multipart_upload_id_idx
    ON assets (multipart_upload_id)
    WHERE multipart_upload_id IS NOT NULL;

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS assets_set_updated_at_trg ON assets;

CREATE TRIGGER assets_set_updated_at_trg
BEFORE UPDATE ON assets
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();


